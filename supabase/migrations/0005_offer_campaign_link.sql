-- Замыкаем круг: оффер рождается из кампании, а принятый отклик
-- превращается в задачу этой кампании.
--
-- До этой миграции офферы и кампании жили отдельно: блогер откликался,
-- агентство нажимало «взять», и дальше ничего не происходило —
-- креатора приходилось руками прикреплять во втором месте.

alter table offers
  add column campaign_id uuid references campaigns(id) on delete set null;

create index offers_campaign_idx on offers (campaign_id);

-- Замечания клиента к подбору и к черновикам ложатся в тот же журнал,
-- что и смены статуса: отдельной ленты комментариев на этом объёме не нужно,
-- а история и так читается сверху вниз.
comment on column campaign_status_log.note is
  'Комментарий к смене статуса: замечание клиента, причина возврата и т.п.';
